"""Cuts decorations and the two new hazards out of the terrain sheet (an opaque illustrated
page) into one transparent atlas, and writes their frames and contact silhouettes.

  python3 scripts/prepare-scenery-art.py
Writes public/assets/art/scenery-<hash>.webp and src/assets/scenery-art.ts. Requires Pillow.
"""
from pathlib import Path
from PIL import Image, ImageFilter, ImageChops
import hashlib, json, math

ROOT = Path(__file__).resolve().parent.parent
SHEET = next((ROOT / 'public/assets/art').glob('terrain-sheet-*.webp'))
# Source rectangles on the 1536x1024 sheet (panel 02 crumbling plank, 07 spikes, 09 decorations).
CUTS = {
    'spikes': (335, 660, 510, 750),
    'crumble': (352, 152, 602, 244),
    'banner': (942, 692, 1040, 904),
    'torch': (1058, 696, 1138, 884),
    'ruins': (1138, 666, 1214, 788),
    'vase': (1132, 786, 1214, 902),
    'sign': (946, 906, 1058, 998),
}
# Hazards keep a contact silhouette at their in-game size (logical pixels).
HAZARD_SIZE = {'spikes': (96, 46), 'crumble': (150, 56)}

sheet = Image.open(SHEET).convert('RGB')


def cut(box):
    im = sheet.crop(box).convert('RGBA')
    # The page is a pale cream: flood it away from the borders, then soften the edge.
    w, h = im.size
    px = im.load()
    bg = [px[x, y][:3] for x, y in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1))]
    def paper(c):
        r, g, b = c[:3]
        light = (r + g + b) / 3 > 196 and max(r, g, b) - min(r, g, b) < 46
        near = min(sum(abs(a - b) for a, b in zip(c[:3], k)) for k in bg) < 60
        return light or near
    seen = set()
    stack = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while stack:
        x, y = stack.pop()
        if (x, y) in seen or not (0 <= x < w and 0 <= y < h) or not paper(px[x, y]):
            continue
        seen.add((x, y))
        px[x, y] = (0, 0, 0, 0)
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    alpha = im.getchannel('A').filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.7))
    im.putalpha(alpha)
    return im.crop(im.getbbox())


parts = {k: cut(v) for k, v in CUTS.items()}
# Pack in one row with a 2px gutter.
x, height = 0, max(p.height for p in parts.values())
atlas = Image.new('RGBA', (sum(p.width + 2 for p in parts.values()), height), (0, 0, 0, 0))
frames = {}
for name, p in parts.items():
    atlas.paste(p, (x, 0))
    frames[name] = {'x': x, 'y': 0, 'w': p.width, 'h': p.height}
    x += p.width + 2
buf = ROOT / 'public/assets/art/scenery.tmp.webp'
atlas.save(buf, 'WEBP', quality=86, method=6, exact=True)
digest = hashlib.sha256(buf.read_bytes()).hexdigest()[:12]
for old in (ROOT / 'public/assets/art').glob('scenery-*.webp'):
    old.unlink()
out = ROOT / f'public/assets/art/scenery-{digest}.webp'
buf.rename(out)

masks = {}
for name, (w, h) in HAZARD_SIZE.items():
    alpha = parts[name].getchannel('A').resize((w, h), Image.Resampling.LANCZOS).filter(ImageFilter.MinFilter(3))
    rows = []
    for y in range(h):
        row, start = [], None
        for xx in range(w + 1):
            solid = xx < w and alpha.getpixel((xx, y)) >= 96
            if solid and start is None:
                start = xx
            elif not solid and start is not None:
                row += [start, xx]
                start = None
        rows.append(row)
    masks['obstacle-' + name] = {'w': w, 'h': h, 'rows': rows}

(ROOT / 'src/assets/scenery-art.ts').write_text(
    '// Generated by scripts/prepare-scenery-art.py from the terrain sheet.\n'
    'import type {ContactMask} from \'./contact-masks\';\n'
    f"export const SCENERY_ART = {json.dumps({'file': f'assets/art/{out.name}', 'frames': frames})} as const;\n"
    f'export const SCENERY_MASKS: Readonly<Record<string, ContactMask>> = {json.dumps(masks, separators=(",", ":"))};\n'
)
print(out.name, {k: (v['w'], v['h']) for k, v in frames.items()}, out.stat().st_size, 'bytes')
