// Optional offline encoding of the two generated PNGs. Build uses committed WebP.
import {readFileSync, writeFileSync, mkdtempSync, rmSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
const [crouch, monsters] = process.argv.slice(2);
if (!crouch || !monsters) throw Error('Pass crouch PNG and monster PNG.');
const hash = b => createHash('sha256').update(b).digest('hex'),
  temporary = mkdtempSync(join(tmpdir(), 'odyssey-expansion-'));
const images = [];
try {
  for (const [name, source, size] of [
    ['crouch', crouch, '768x512'],
    ['monsters', monsters, '1536x1024'],
  ]) {
    const bytes = readFileSync(source),
      out = join(temporary, name + '.webp');
    const r = spawnSync('convert', [source, '-resize', size, '-strip', '-define', 'webp:lossless=true', out], {
      encoding: 'utf8',
    });
    if (r.status !== 0) throw Error(r.stderr);
    const encoded = readFileSync(out),
      sha = hash(encoded),
      file = `assets/art/${name}-${sha.slice(0, 12)}.webp`;
    writeFileSync('public/' + file, encoded);
    images.push({name, file, bytes: encoded.length, sha256: sha, sourceSha256: hash(bytes), size});
  }
  const crouchArt = {
    file: images[0].file,
    frame: {x: 100, y: 50, w: 585, h: 424},
    originX: 280 / 585,
    originY: 419 / 424,
    scale: 36 / 414.5,
  };
  const monsterArt = {
    file: images[1].file,
    frames: {
      crab: {x: 20, y: 72, w: 492, h: 408},
      harpy: {x: 528, y: 16, w: 524, h: 490},
      stone: {x: 1068, y: 24, w: 452, h: 474},
      scylla: {x: 16, y: 520, w: 506, h: 480},
      cyclops: {x: 532, y: 520, w: 488, h: 480},
      shade: {x: 1056, y: 516, w: 472, h: 480},
    },
  };
  writeFileSync(
    'src/assets/expansion-art.ts',
    `// Generated by prepare-expansion-art.mjs; rendering frames only.\nexport const CROUCH_ART = ${JSON.stringify(crouchArt, null, 2)} as const;\nexport const MONSTER_ART = ${JSON.stringify(monsterArt, null, 2)} as const;\n`,
  );
  writeFileSync(
    'docs/expansion-art-manifest.json',
    JSON.stringify(
      {
        created: '2026-10-26',
        provenance:
          'image_gen, referencing the supplied Odysseus portrait and sea monster design sheet. Separate low crouch and six transparent monster designs. No runtime API.',
        processing:
          'Aspect-preserving preparation and lossless WebP after resize; alpha preserved; frame extraction at render time.',
        images,
        crouchArt,
        monsterArt,
      },
      null,
      2,
    ) + '\n',
  );
  console.log(JSON.stringify(images.map(({name, bytes, file}) => ({name, bytes, file}))));
} finally {
  rmSync(temporary, {recursive: true, force: true});
}
