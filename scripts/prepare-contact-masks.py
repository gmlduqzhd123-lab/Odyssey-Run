"""Offline contact silhouettes from the committed artwork; no runtime pixel reads.

Invoked by prepare-contact-masks.ts; requires Python Pillow. Does not alter images.
"""
from pathlib import Path
from PIL import Image, ImageFilter
import json, math, hashlib, sys

def constant(path, name):
    text=Path(path).read_text().split('export const '+name+' = ',1)[1]
    return json.loads(text.split(' as const;',1)[0])

files=constant('src/assets/files.ts','ART_FILES')
run=constant('src/assets/runner-art.ts','RUN_ART')
crouch=constant('src/assets/expansion-art.ts','CROUCH_ART')
monsters=constant('src/assets/expansion-art.ts','MONSTER_ART')
sources={}
def image(file):
    path=Path('public')/file
    sources[file]=hashlib.sha256(path.read_bytes()).hexdigest()
    if path.suffix=='.svg':
        return Image.open(Path(sys.argv[1])/(path.stem+'.png')).convert('RGBA')
    return Image.open(path).convert('RGBA')

masks={}
def add(name,im,w,h):
    # Ignore soft fringes; one logical pixel of inward tolerance on each side.
    alpha=im.getchannel('A').resize((math.ceil(w),math.ceil(h)),Image.Resampling.LANCZOS)
    alpha=alpha.filter(ImageFilter.MinFilter(3))
    rows=[]
    for y in range(alpha.height):
        row=[];start=None
        for x in range(alpha.width+1):
            solid=x<alpha.width and alpha.getpixel((x,y))>=96
            if solid and start is None:start=x
            elif not solid and start is not None:row.extend((start,x));start=None
        rows.append(row)
    masks[name]={'w':alpha.width,'h':alpha.height,'rows':rows}

sheet=image(run['file'])
for i,f in enumerate(run['frames']):add('run-'+str(i),sheet.crop((f['x'],f['y'],f['x']+f['w'],f['y']+f['h'])),f['w']*run['scale'],f['h']*run['scale'])
f=crouch['frame'];im=image(crouch['file']);add('crouch',im.crop((f['x'],f['y'],f['x']+f['w'],f['y']+f['h'])),f['w']*crouch['scale'],f['h']*crouch['scale'])
add('air',image(files['odysseus']),66,88)
sheet=image(monsters['file'])
for kind,f in monsters['frames'].items():
    scale=min(96/f['w'],(108 if kind=='cyclops' else 76)/f['h'])
    add(kind,sheet.crop((f['x'],f['y'],f['x']+f['w'],f['y']+f['h'])),f['w']*scale,f['h']*scale)
for kind in ['star','shield','wings','magnet','apple','map','trident','compass','lantern']:
    size=24 if kind=='star' else 36
    add(kind,image(files.get(kind,'assets/'+kind+'.svg')),size,size)
add('projectile',image('assets/rock.svg'),36,28)
Path('src/assets/contact-masks.ts').write_text('// Generated by scripts/prepare-contact-masks.py from committed artwork.\n'
    +'export interface ContactMask {w:number;h:number;rows:readonly (readonly number[])[];}\n'
    +'export const CONTACT_MASKS:Readonly<Record<string,ContactMask>> = '+json.dumps(masks,separators=(',',':'))+';\n')
Path('docs/contact-mask-manifest.json').write_text(json.dumps({'resolution':'one logical pixel; alpha >= 96 after inward 3x3 min filter','sourceSha256':sources,'maskCount':len(masks),'policy':'Keep original movement body; require opaque hero and target contact inside both original bodies for damage. Magnet remains star-only.'},ensure_ascii=False,indent=2)+'\n')
print('Generated',len(masks),'contact silhouettes; original assets unchanged.')
