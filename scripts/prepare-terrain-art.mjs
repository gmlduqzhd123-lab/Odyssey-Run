// Optional offline encoding only. Sheet regions are selected at render time.
// node scripts/prepare-terrain-art.mjs '플랫포머 게임 지형·오브젝트 도감.zip'
import {readFileSync,writeFileSync,mkdirSync,mkdtempSync,rmSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
const archive=process.argv[2];if(!archive)throw Error('Pass the terrain ZIP path.');
const sources=[['terrain-sheet','플랫포머 게임 지형·오브젝트 도감.png'],['enemy-sheet','오디세이 해양 몬스터 디자인 시트-2.png'],['myth-sheet','오디세이 몬스터 도감-1.png'],['landscape-sheet','다채로운 판타지 플랫폼 게임 배경 타일 시트.png'],['sea-sheet','바다 신화 몬스터 도감 10종-3.png']];
const hash=b=>createHash('sha256').update(b).digest('hex');
const temporary=mkdtempSync(join(tmpdir(),'odyssey-terrain-')),files={},images=[];
try{
 mkdirSync('public/assets/art',{recursive:true});
 const listing=spawnSync('unzip',['-Z1',archive],{encoding:'utf8'});if(listing.status!==0)throw Error('Could not read ZIP.');
 const entries=listing.stdout.split('\n');
 for(const [name,sourceFile] of sources){
  if(entries.filter(e=>e===sourceFile).length!==1)throw Error('Missing or duplicate source sheet.');
  const unpack=spawnSync('unzip',['-p',archive,sourceFile],{maxBuffer:16*1024*1024});if(unpack.status!==0)throw Error('Could not read PNG.');
  const bytes=unpack.stdout;if(!bytes.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]))||bytes.readUInt32BE(16)!==1536||bytes.readUInt32BE(20)!==1024)throw Error('Unexpected PNG dimensions.');
  const input=join(temporary,name+'.png'),output=join(temporary,name+'.webp');writeFileSync(input,bytes);
  const encoded=spawnSync('convert',[input,'-strip','-quality','90',output],{encoding:'utf8'});if(encoded.status!==0)throw Error(encoded.stderr);
  const result=readFileSync(output),digest=hash(result);files[name]=`assets/art/${name}-${digest.slice(0,12)}.webp`;writeFileSync('public/'+files[name],result);
  images.push({name,sourceFile,sourceBytes:bytes.length,sourceSha256:hash(bytes),size:[1536,1024],displayTexture:files[name],preparedBytes:result.length,preparedSha256:digest});
 }
 writeFileSync('src/assets/terrain-files.ts',`// Generated by scripts/prepare-terrain-art.mjs.\nexport const TERRAIN_FILES = ${JSON.stringify(files,null,2)} as const;\n`);
 writeFileSync('docs/terrain-art-manifest.json',JSON.stringify({archive:'플랫포머 게임 지형·오브젝트 도감.zip',processing:'Whole-sheet WebP quality 90 encoding, original resolution, no redraw or background removal. Runtime atlas rectangles are in src/assets/terrain.ts.',images},null,2)+'\n');
 console.log(JSON.stringify({sheets:images.length,sourceBytes:images.reduce((n,i)=>n+i.sourceBytes,0),preparedBytes:images.reduce((n,i)=>n+i.preparedBytes,0)}));
}finally{rmSync(temporary,{recursive:true,force:true});}
